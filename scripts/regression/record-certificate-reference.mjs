// Run against an installation of the frozen 5d53b9aa7 backend package.json.
// Writes a candidate to the explicitly supplied path; never blesses results.
import assert from 'node:assert/strict';
import { generateKeyPairSync } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';

const require = createRequire(resolve(process.argv[2]));
assert.equal(require('jsrsasign/package.json').version, '11.1.5');
const jsrsasign = require('jsrsasign');
const certificates = {};
for (const [family, algorithm] of [['rsa', 'SHA256withRSA'], ['ec', 'SHA256withECDSA']]) {
	const options = family === 'rsa' ? { modulusLength: 2048 } : { namedCurve: 'prime256v1' };
	const root = generateKeyPairSync(family, options);
	const intermediate = generateKeyPairSync(family, options);
	const leaf = generateKeyPairSync(family, options);
	const issue = (name, subject, issuer, key, signingKey, expired = false) => {
		certificates[name] = new jsrsasign.KJUR.asn1.x509.Certificate({
			version: 3, serial: { int: Object.keys(certificates).length + 1 }, sigalg: algorithm,
			issuer: { str: issuer }, subject: { str: subject },
			notbefore: '20200101000000Z', notafter: expired ? '20210101000000Z' : '20400101000000Z',
			sbjpubkey: key.publicKey.export({ type: 'spki', format: 'pem' }),
			cakey: signingKey.privateKey.export({ type: 'pkcs8', format: 'pem' }),
		}).getPEM();
	};
	issue(`${family}-root`, '/C=JP/O=Maintenance/CN=Fixture root', '/C=JP/O=Maintenance/CN=Fixture root', root, root);
	issue(`${family}-intermediate`, '/C=JP/O=Maintenance/CN=Fixture intermediate', '/C=JP/O=Maintenance/CN=Fixture root', intermediate, root);
	issue(`${family}-leaf`, '/C=JP/O=Maintenance/CN=attest.android.com', '/C=JP/O=Maintenance/CN=Fixture intermediate', leaf, intermediate);
	issue(`${family}-expired`, '/CN=attest.android.com', '/C=JP/O=Maintenance/CN=Fixture root', leaf, root, true);
	issue(`${family}-duplicate-cn`, '/CN=first.invalid/CN=attest.android.com', '/C=JP/O=Maintenance/CN=Fixture root', leaf, root);
	const der = Buffer.from(certificates[`${family}-leaf`].replace(/-----[^-]+-----|\s/g, ''), 'base64');
	der[der.length - 1] ^= 1;
	certificates[`${family}-tampered`] = `-----BEGIN CERTIFICATE-----\n${der.toString('base64')}\n-----END CERTIFICATE-----\n`;
}
certificates.malformed = '-----BEGIN CERTIFICATE-----\nnot-a-certificate\n-----END CERTIFICATE-----';
// Include the real SHA-1-signed root already embedded in this fork. Keeping its
// historical signature-only result does not assert that its trust policy is safe.
const serviceSource = await readFile(new URL('../../packages/backend/src/core/TwoFactorAuthenticationService.ts', import.meta.url), 'utf8');
const rootMatch = /const GSR2 = `([^`]+)`;/.exec(serviceSource);
assert.ok(rootMatch, 'Missing reference SafetyNet root');
certificates['safetynet-root'] = rootMatch[1].replaceAll('\\n', '\n');

// The two functions below are the implementation in TwoFactorAuthenticationService
// at the reference revision, without TypeScript annotations/non-null assertions.
function getCertSubject(pem) {
	const cert = new jsrsasign.X509(); cert.readCertPEM(pem);
	const fields = {};
	for (const field of cert.getSubjectString().slice(1).split('/')) {
		const eq = field.indexOf('='); fields[field.substring(0, eq)] = field.substring(eq + 1);
	}
	return fields;
}
function verifyCertificateChain(chain) {
	let valid = true;
	for (let i = 0; i < chain.length; i++) {
		const cert = new jsrsasign.X509(); cert.readCertPEM(chain[i]);
		const tbs = jsrsasign.ASN1HEX.getTLVbyList(cert.hex, 0, [0]);
		if (tbs == null) throw new Error('certStruct is null');
		const signature = new jsrsasign.KJUR.crypto.Signature({ alg: cert.getSignatureAlgorithmField() });
		signature.init(chain[i + 1] ?? chain[i]); signature.updateHex(tbs);
		valid = valid && !!signature.verify(cert.getSignatureValueHex());
	}
	return valid;
}
const observe = operation => { try { return { value: operation() }; } catch { return { throws: true }; } };
const chains = [[]];
for (const family of ['rsa', 'ec']) {
	chains.push([`${family}-root`], [`${family}-leaf`, `${family}-intermediate`, `${family}-root`],
		[`${family}-expired`, `${family}-root`], [`${family}-duplicate-cn`, `${family}-root`],
		[`${family}-tampered`, `${family}-intermediate`, `${family}-root`],
		[`${family}-leaf`, `${family}-root`], [`${family}-leaf`],
		[`${family}-root`, `${family}-intermediate`, `${family}-leaf`]);
}
chains.push(['rsa-leaf', 'ec-root'], ['malformed'], ['rsa-leaf', 'malformed'], ['safetynet-root']);
const fixture = {
	reference: '5d53b9aa77b29c275c5fa570746099121a94a672',
	description: 'Public test certificates generated by jsrsasign 11.1.5. No private keys retained. Expected results from the unmodified reference helpers. Expiry/trust policy intentionally unchanged.',
	certificates,
	subjects: Object.keys(certificates).map(name => ({ name, expected: observe(() => getCertSubject(certificates[name])) })),
	chains: chains.map(chain => ({ chain, expected: observe(() => verifyCertificateChain(chain.map(name => certificates[name]))) })),
};
assert.ok(process.argv[3], 'An explicit candidate output path is required');
await writeFile(process.argv[3], JSON.stringify(fixture, null, 2) + '\n');
